DB_PATH = pathlib.Path("/data/scoring.db")
SCHEMA = pathlib.Path(__file__).with_name("schema.sql")
MQTT_HOST = os.environ.get("MQTT_HOST", "bus")
MQTT_PORT = int(os.environ.get("MQTT_PORT", "1883"))

NAME_RE = re.compile(r"^[A-Za-z0-9_.-]{3,20}$")

app = Flask(__name__)
_alert_level = 0
_mqtt: mqtt.Client | None = None


# -- infra -----------------------------------------------------------------
def db() -> sqlite3.Connection:
    if "db" not in g:
        g.db = sqlite3.connect(DB_PATH)
        g.db.row_factory = sqlite3.Row
        g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


@app.teardown_appcontext
def _close_db(_exc):
    d = g.pop("db", None)
    if d is not None:
        d.close()


def init_db() -> None:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH)
    conn.executescript(SCHEMA.read_text())
    conn.commit()
    conn.close()


def mqtt_connect() -> None:
    global _mqtt
    _mqtt = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, client_id="scoring")
    if os.environ.get("MQTT_USER"):
        _mqtt.username_pw_set(os.environ["MQTT_USER"], os.environ.get("MQTT_PASS", ""))

    def on_connect(c, u, flags_, rc, props):
        c.subscribe("pkt/alert/level")
        c.subscribe("pkt/creds/rotate")

    def on_message(c, u, msg):
        global _alert_level
        if msg.topic == "pkt/creds/rotate":
            try:
                import creds
                creds.generate()
                c.publish("pkt/creds/changed", "{}")
            except Exception as exc:
                print("[scoring] cred rotate:", exc)
            return
        try:
            _alert_level = int(json.loads(msg.payload.decode() or "{}").get("level", 0))
        except Exception:
            pass

    _mqtt.on_connect = on_connect
    _mqtt.on_message = on_message
    for _ in range(30):
        try:
            _mqtt.connect(MQTT_HOST, MQTT_PORT, keepalive=30)
            break
        except OSError:
            time.sleep(2)
    _mqtt.loop_start()


def publish(topic: str, payload: dict) -> None:
    if _mqtt is not None:
        _mqtt.publish(topic, json.dumps(payload))


def current_user() -> dict | None:
    return auth.read_session(request.headers.get("Cookie"))


def active_run(user_id: int) -> sqlite3.Row | None:
    return db().execute(
        "SELECT * FROM runs WHERE user_id=? ORDER BY id DESC LIMIT 1", (user_id,)
    ).fetchone()


def run_total(run_id: int) -> int:
    r = db().execute(
        "SELECT COALESCE(SUM(points),0) AS t FROM submissions WHERE run_id=?", (run_id,)
    ).fetchone()
    return int(r["t"])


