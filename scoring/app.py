"""Packet River scoring service.

Owns the flags (generated by flags.py at boot), the accounts, the runs, and the
leaderboard. The only way to score is to submit a real flag string that exists
only inside the vulnerable resource it was planted in; there is no
"award points" endpoint. On a valid submission it publishes pkt/score/events so
simmap breaks that part of the town.
"""
from __future__ import annotations

