# -- accounts ----------------------------------------------------------
@app.post("/api/score/register")
def register():
    data = request.get_json(force=True, silent=True) or {}
    name = (data.get("name") or "").strip()
    pw = data.get("password") or ""
    if not NAME_RE.match(name):
        return {"error": "name must be 3-20 chars, letters/digits/._-"}, 400
    if len(pw) < 6:
        return {"error": "password must be at least 6 characters"}, 400
    try:
        cur = db().execute(
            "INSERT INTO users (name, pw_hash) VALUES (?,?)",
            (name, auth.hash_password(pw)),
        )
        db().execute("INSERT INTO scores (user_id) VALUES (?)", (cur.lastrowid,))
        db().commit()
    except sqlite3.IntegrityError:
        return {"error": "that name is taken"}, 409
    resp = jsonify({"name": name})
    resp.headers["Set-Cookie"] = auth.make_cookie(cur.lastrowid, name)
    return resp


@app.post("/api/score/login")
def login():
    data = request.get_json(force=True, silent=True) or {}
    name = (data.get("name") or "").strip()
    pw = data.get("password") or ""
    row = db().execute("SELECT * FROM users WHERE name=?", (name,)).fetchone()
    if not row or not auth.verify_password(pw, row["pw_hash"]):
        return {"error": "wrong name or password"}, 401
    resp = jsonify({"name": name})
    resp.headers["Set-Cookie"] = auth.make_cookie(row["id"], name)
    return resp


@app.post("/api/score/logout")
def logout():
    resp = jsonify({"ok": True})
    resp.headers["Set-Cookie"] = auth.clear_cookie()
    return resp


@app.get("/api/score/me")
def me():
    u = current_user()
    if not u:
        return {"anon": True, "alert_level": _alert_level}
    s = db().execute(
        "SELECT total, best_run_total FROM scores WHERE user_id=?", (u["uid"],)
    ).fetchone()
    run = active_run(u["uid"])
    return {
        "name": u["name"],
        "total": s["total"] if s else 0,
        "best": s["best_run_total"] if s else 0,
        "alert_level": _alert_level,
        "active_run": {"id": run["id"], "score_so_far": run_total(run["id"])} if run else None,
    }


# -- runs + scoring --------------------------------------------------
@app.post("/api/score/run")
def start_run():
    u = current_user()
    if not u:
        return {"error": "log in first"}, 401
    cur = db().execute(
        "INSERT INTO runs (user_id, started_ts) VALUES (?,?)", (u["uid"], time.time())
    )
    db().commit()
    return {"run_id": cur.lastrowid}


@app.post("/api/score/arm")
def arm():
    u = current_user()
    if not u:
        return {"error": "log in first"}, 401
    tid = (request.get_json(force=True, silent=True) or {}).get("technique_id", "")
    run = active_run(u["uid"])
    if not run:
        return {"error": "start a run first"}, 409
    if not db().execute("SELECT 1 FROM flags WHERE technique_id=?", (tid,)).fetchone():
        return {"error": "unknown technique"}, 404
    db().execute(
        "INSERT OR REPLACE INTO armed (run_id, technique_id, armed_at, alert_at_arm) "
        "VALUES (?,?,?,?)",
        (run["id"], tid, time.time(), _alert_level),
    )
    db().commit()
    return {"armed": True, "technique_id": tid}


@app.post("/api/score/submit")
def submit():
    u = current_user()
    if not u:
        return {"error": "log in first"}, 401
    flag = ((request.get_json(force=True, silent=True) or {}).get("flag") or "").strip()
    run = active_run(u["uid"])
    if not run:
        return {"error": "start a run first"}, 409

    match = None
    for row in db().execute("SELECT * FROM flags").fetchall():
        if hmac.compare_digest(flag, row["flag"]):
            match = row
            break
    if not match:
        publish("pkt/score/events", {"type": "reject", "user": u["name"]})
        return {"accepted": False}

    dup = db().execute(
        "SELECT 1 FROM submissions WHERE run_id=? AND technique_id=?",
        (run["id"], match["technique_id"]),
    ).fetchone()
    if dup:
        return {"accepted": False, "detail": "already claimed this run"}

    armed = db().execute(
        "SELECT armed_at, alert_at_arm FROM armed WHERE run_id=? AND technique_id=?",
        (run["id"], match["technique_id"]),
    ).fetchone()
    started = armed["armed_at"] if armed else run["started_ts"]
    alert_at_arm = armed["alert_at_arm"] if armed else _alert_level
    elapsed = max(0.0, time.time() - started)

    prior = db().execute(
        "SELECT COUNT(DISTINCT s.technique_id) AS n FROM submissions s "
        "JOIN flags f ON f.technique_id = s.technique_id "
        "WHERE s.run_id=? AND f.subsystem=?",
        (run["id"], match["subsystem"]),
    ).fetchone()["n"]

    points, breakdown = compute(match["base"], alert_at_arm, _alert_level, prior, elapsed)

    db().execute(
        "INSERT INTO submissions "
        "(run_id, user_id, technique_id, points, stealth, chain_n, elapsed_s) "
        "VALUES (?,?,?,?,?,?,?)",
        (run["id"], u["uid"], match["technique_id"], points,
         breakdown["stealth"], prior, elapsed),
    )
    rt = run_total(run["id"])
    db().execute(
        "UPDATE scores SET total = total + ?, "
        "best_run_total = MAX(best_run_total, ?) WHERE user_id=?",
        (points, rt, u["uid"]),
    )
    db().commit()

    publish("pkt/score/events", {
        "technique_id": match["technique_id"],
        "target": match["target"],
        "shop": match["target"],
        "effect": match["effect"],
        "severity": match["severity"],
        "subsystem": match["subsystem"],
        "user": u["name"],
        "run_id": run["id"],
    })

    total = db().execute(
        "SELECT total FROM scores WHERE user_id=?", (u["uid"],)
    ).fetchone()["total"]
    return {
        "accepted": True,
        "points": points,
        "breakdown": breakdown,
        "target": match["target"],
        "run_total": rt,
        "new_total": total,
    }


@app.get("/api/score/leaderboard")
def leaderboard():
    rows = db().execute(
        "SELECT u.name, s.best_run_total, s.total "
        "FROM scores s JOIN users u ON u.id = s.user_id "
        "WHERE s.best_run_total > 0 OR s.total > 0 "
        "ORDER BY s.best_run_total DESC, s.total DESC LIMIT 25"
    ).fetchall()
    return jsonify([dict(r) for r in rows])


